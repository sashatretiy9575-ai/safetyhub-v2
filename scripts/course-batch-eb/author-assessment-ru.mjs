export function buildAssessment() {
  return {
    schemaVersion: 1,
    slug: SLUG,
    locale: 'ru',
    status: 'draft-awaiting-independent-review',
    policy: {
      durationMinutes: 15,
      passScore: 7,
      questionCount: 10,
      variantCount: 3,
      attemptsPerCalendarDay: 8,
      resetTimezone: 'Asia/Oral',
    },
    variants: VARIANTS.map((questions, vi) => ({
      id: nameUuid(`variant:${vi + 1}`),
      variantNumber: vi + 1,
      questions: questions.map(([slide, text, correct, wrong, explanation, at], qi) => {
        const key = `v${vi + 1}:q${qi + 1}`;
        const texts = [...wrong];
        texts.splice(at - 1, 0, correct);
        const options = texts.map((option, oi) => ({
          id: nameUuid(`${key}:o${oi + 1}`),
          text: option,
          displayOrder: oi + 1,
        }));
        return {
          id: nameUuid(key),
          text,
          displayOrder: qi + 1,
          options,
          correctOptionId: options[at - 1].id,
          explanation,
          slideRefs: [`slide-${String(slide).padStart(2, '0')}`],
        };
      }),
    })),
  };
}

if (
  import.meta.url === `file:///${process.argv[1]?.replaceAll('\\', '/')}` ||
  process.argv[1]?.endsWith('author-assessment-ru.mjs')
) {
  const file = `content/course-batch-2026-09-eb/${SLUG}/ru/assessment.json`;
  await writeFile(file, JSON.stringify(buildAssessment(), null, 2) + '\n');
  console.log('written', file);
}
