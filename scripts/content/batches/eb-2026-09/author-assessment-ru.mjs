export function buildAssessment(slug) {
  const variants = COURSES[slug];
  if (!variants) throw new Error('UNKNOWN_COURSE:' + slug);
  return {
    schemaVersion: 1,
    slug,
    locale: 'ru',
    status: 'draft-awaiting-independent-review',
    policy: {
      durationMinutes: 15,
      passScore: 7,
      questionCount: 10,
      variantCount: 3,
      attemptsPerCalendarDay: 8,
      resetTimezone: 'Asia/Oral',
    },
    variants: variants.map((questions, vi) => ({
      id: nameUuid(slug, `variant:${vi + 1}`),
      variantNumber: vi + 1,
      questions: questions.map(([slide, text, correct, wrong, explanation, at], qi) => {
        const key = `v${vi + 1}:q${qi + 1}`;
        const texts = [...wrong];
        texts.splice(at - 1, 0, correct);
        const options = texts.map((option, oi) => ({
          id: nameUuid(slug, `${key}:o${oi + 1}`),
          text: option,
          displayOrder: oi + 1,
        }));
        return {
          id: nameUuid(slug, key),
          text,
          displayOrder: qi + 1,
          options,
          correctOptionId: options[at - 1].id,
          explanation,
          slideRefs: [`slide-${String(slide).padStart(2, '0')}`],
        };
      }),
    })),
  };
}

if (process.argv[1]?.endsWith('author-assessment-ru.mjs')) {
  for (const slug of SLUGS) {
    const file = `content/course-batch-2026-09-eb/${slug}/ru/assessment.json`;
    await writeFile(file, JSON.stringify(buildAssessment(slug), null, 2) + '\n');
    console.log('written', file);
  }
}
